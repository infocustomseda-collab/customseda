#!/usr/bin/env node
// Utopia-style fluid type and space scales (https://utopia.fyi). Values are anchored on the
// current-storefront audit in docs/design/visual-audit.md. Regenerate with `pnpm design:fluid`.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const VIEWPORT = { min: 360, max: 1440 };
// Body 17px with a 1.2 ratio on small screens; 18px with a 1.29 ratio at 1440px, which keeps
// headings at the audited 36px mobile / 48px desktop and page titles at about 62px.
export const TYPE = { min: { size: 17, ratio: 1.2 }, max: { size: 18, ratio: 1.29 }, steps: [-1, 0, 1, 2, 3, 4, 5] };
export const SPACE = {
 sizes: { '3xs': 0.25, '2xs': 0.5, xs: 0.75, s: 1, m: 1.5, l: 2, xl: 3, '2xl': 4, '3xl': 6 },
 // Custom pairs: s-l grid gaps, s-xl page gutters, m-xl band padding, m-2xl section separation.
 custom: [['s', 'l'], ['s', 'xl'], ['m', 'xl'], ['m', '2xl']],
};

const round = (value, places = 4) => Number(value.toFixed(places));
const rem = px => round(px / 16);

export function fluid(minPx, maxPx, { min, max } = VIEWPORT) {
 const slope = (maxPx - minPx) / (max - min);
 const intercept = minPx - slope * min;
 return `clamp(${rem(Math.min(minPx, maxPx))}rem, ${rem(intercept)}rem + ${round(slope * 100)}vw, ${rem(Math.max(minPx, maxPx))}rem)`;
}

export const typeScale = () => TYPE.steps.map(step => ({
 step,
 min: TYPE.min.size * TYPE.min.ratio ** step,
 max: TYPE.max.size * TYPE.max.ratio ** step,
}));

export function spaceScale() {
 const entries = Object.entries(SPACE.sizes);
 const size = name => ({ min: TYPE.min.size * SPACE.sizes[name], max: TYPE.max.size * SPACE.sizes[name] });
 const sizes = entries.map(([name]) => ({ name, ...size(name) }));
 const oneUp = entries.slice(0, -1).map(([name], i) => [name, entries[i + 1][0]]);
 const pairs = [...oneUp, ...SPACE.custom].map(([from, to]) => ({ name: `${from}-${to}`, min: size(from).min, max: size(to).max }));
 return { sizes, pairs };
}

export function renderFluidCss() {
 const { sizes, pairs } = spaceScale();
 return [
  '/* Generated by scripts/design/fluid-scale.mjs — do not edit by hand. */',
  `/* Utopia scales: ${VIEWPORT.min}px → ${VIEWPORT.max}px viewport. */`,
  '@layer tokens {',
  ' :root {',
  ...typeScale().map(s => `  --step-${s.step}: ${fluid(s.min, s.max)};`),
  '',
  ...sizes.map(s => `  --space-${s.name}: ${fluid(s.min, s.max)};`),
  '',
  ...pairs.map(p => `  --space-${p.name}: ${fluid(p.min, p.max)};`),
  ' }',
  '}',
  '',
 ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
 const target = new URL('../../src/styles/global/fluid.css', import.meta.url);
 writeFileSync(target, renderFluidCss());
 console.log(`Wrote ${fileURLToPath(target)}`);
}
